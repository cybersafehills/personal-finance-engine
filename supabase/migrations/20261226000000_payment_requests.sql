-- OneLedger 3.0 S5: payment requests, Stage 1 (NON-CUSTODIAL; docs/oneledger-3/
-- contracts.md, security.md). A payment request is a shareable "please pay me
-- this" record. OneLedger never holds or moves money and never initiates a
-- payment. Hard rules enforced HERE, not in the UI:
--   * a request is never "paid" because a link was opened or a payer claimed it;
--     the only terminal-success states are 'marked_paid_by_owner' (the owner's
--     own assertion, labelled as such) and 'matched' (a human links a real,
--     settled, equal-amount INCOMING transaction in the same workspace);
--   * the public resolver exposes the minimum needed to pay and nothing about
--     the workspace, the owner, or any history;
--   * the secret token is generated by the application and NEVER stored or seen
--     by the database - only its SHA-256 hex digest is (same pattern as
--     invite_preview). Expiry is evaluated at read time, so it needs no cron.

create table public.payment_requests (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  created_by uuid references auth.users (id) on delete set null,
  amount_minor bigint not null check (amount_minor > 0 and amount_minor <= 1000000000000),
  currency char(3) not null check (currency in ('RWF', 'USD', 'EUR')),
  destination_type text not null check (destination_type in ('momo_phone', 'merchant_code')),
  -- momo_phone: normalised 2507XXXXXXXX; merchant_code: 4-8 digits.
  destination_value text not null,
  recipient_display text not null check (length(recipient_display) between 1 and 80
                                         and recipient_display !~ '[[:cntrl:]]'),
  reference text check (reference is null or (length(reference) <= 64 and reference !~ '[[:cntrl:]]')),
  expires_at timestamptz not null,
  -- 'expired' is derived (see payment_requests_v), never stored.
  status text not null default 'open'
    check (status in ('open', 'cancelled', 'marked_paid_by_owner', 'matched')),
  token_hash text not null check (token_hash ~ '^[0-9a-f]{64}$'),
  idempotency_key text check (idempotency_key is null or length(idempotency_key) between 8 and 100),
  matched_transaction_id uuid,
  cancelled_at timestamptz,
  paid_marked_at timestamptz,
  paid_marked_note text check (paid_marked_note is null or length(paid_marked_note) <= 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint payment_requests_token_hash_unique unique (token_hash),
  constraint payment_requests_expiry_after_creation check (expires_at > created_at),
  constraint payment_requests_destination_valid check (
    (destination_type = 'momo_phone' and destination_value ~ '^2507[0-9]{8}$')
    or (destination_type = 'merchant_code' and destination_value ~ '^[0-9]{4,8}$')),
  constraint payment_requests_matched_consistent check (
    (status = 'matched') = (matched_transaction_id is not null)),
  constraint payment_requests_matched_txn_same_workspace
    foreign key (workspace_id, matched_transaction_id)
    references public.transactions (workspace_id, id) on delete set null (matched_transaction_id)
);
-- NOTE: the "matched" check above would fail if the FK nulled the column while
-- status stays 'matched'; transactions are never hard-deleted by the app, and
-- erasure removes the whole workspace (cascade) - so this is an intentional
-- loud failure rather than a silent downgrade of a settled request.

create unique index idx_payment_requests_idem
  on public.payment_requests (workspace_id, idempotency_key) where idempotency_key is not null;
create unique index idx_payment_requests_matched_txn
  on public.payment_requests (matched_transaction_id) where matched_transaction_id is not null;
create index idx_payment_requests_workspace_created
  on public.payment_requests (workspace_id, created_at desc);
create trigger set_payment_requests_updated_at
  before update on public.payment_requests
  for each row execute function public.set_updated_at();

create table public.payment_request_events (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  payment_request_id uuid not null references public.payment_requests (id) on delete cascade,
  event_type text not null check (event_type in ('created', 'cancelled', 'marked_paid_by_owner', 'matched')),
  actor_user_id uuid references auth.users (id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index idx_payment_request_events_request on public.payment_request_events (payment_request_id, created_at);

alter table public.payment_requests enable row level security;
alter table public.payment_request_events enable row level security;
create policy payment_requests_select_member on public.payment_requests
  for select to authenticated using (public.is_workspace_member(workspace_id));
create policy payment_request_events_select_member on public.payment_request_events
  for select to authenticated using (public.is_workspace_member(workspace_id));
revoke all on public.payment_requests, public.payment_request_events from anon, authenticated;
grant select on public.payment_requests, public.payment_request_events to authenticated;
grant select, insert, update, delete on public.payment_requests, public.payment_request_events to service_role;

comment on table public.payment_requests is
  'Non-custodial payment requests. Written only via create_/cancel_/mark_paid_/link_ RPCs. token_hash is SHA-256 hex of an app-generated secret the DB never sees. Status never means "paid" unless the owner says so (marked_paid_by_owner) or a human links a matching settled incoming transaction (matched).';

-- Read model with the derived 'expired' state (security_invoker: caller's RLS).
create view public.payment_requests_v
with (security_invoker = true) as
select
  r.id, r.workspace_id, r.created_by, r.amount_minor, r.currency, r.destination_type,
  r.destination_value, r.recipient_display, r.reference, r.expires_at,
  case when r.status = 'open' and r.expires_at <= now() then 'expired' else r.status end as status,
  r.matched_transaction_id, r.cancelled_at, r.paid_marked_at, r.created_at
from public.payment_requests r;
grant select on public.payment_requests_v to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- create_payment_request. Member+. Validates everything server-side (client
-- values are never trusted). Limits: 30 creations / user / hour, 200 open per
-- workspace. Idempotent on (workspace, key): a retry returns the existing id.
-- The caller keeps its own token; only the digest is sent here.
-- ---------------------------------------------------------------------------
create or replace function public.create_payment_request(
  p_workspace_id uuid,
  p_amount_minor bigint,
  p_currency text,
  p_destination_type text,
  p_destination_value text,
  p_recipient_display text,
  p_reference text,
  p_expires_at timestamptz,
  p_token_hash text,
  p_idempotency_key text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_dest text;
  v_id uuid;
  v_display text := trim(p_recipient_display);
  v_ref text := nullif(trim(p_reference), '');
begin
  if auth.uid() is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;
  if not public.is_workspace_member(p_workspace_id, 'member') then
    raise exception 'workspace_not_found' using errcode = 'P0002';
  end if;

  -- Idempotent retry (same workspace + key) returns the original request.
  if p_idempotency_key is not null then
    select id into v_id from public.payment_requests
    where workspace_id = p_workspace_id and idempotency_key = p_idempotency_key;
    if found then return v_id; end if;
  end if;

  if p_amount_minor is null or p_amount_minor <= 0 or p_amount_minor > 1000000000000
     or p_currency not in ('RWF', 'USD', 'EUR')
     or v_display is null or length(v_display) not between 1 and 80 or v_display ~ '[[:cntrl:]]'
     or (v_ref is not null and (length(v_ref) > 64 or v_ref ~ '[[:cntrl:]]'))
     or p_token_hash is null or p_token_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'invalid_payment_request' using errcode = '22023';
  end if;
  if p_expires_at is null or p_expires_at <= now() + interval '1 minute'
     or p_expires_at > now() + interval '90 days' then
    raise exception 'invalid_expiry' using errcode = '22023';
  end if;

  if p_destination_type = 'momo_phone' then
    v_dest := public.normalize_msisdn(p_destination_value);
  elsif p_destination_type = 'merchant_code' and p_destination_value ~ '^[0-9]{4,8}$' then
    v_dest := p_destination_value;
  end if;
  if v_dest is null then
    raise exception 'invalid_destination' using errcode = '22023';
  end if;

  if (select count(*) from public.payment_requests
        where created_by = auth.uid() and created_at > now() - interval '1 hour') >= 30 then
    raise exception 'rate_limited' using errcode = '54000';
  end if;
  if (select count(*) from public.payment_requests
        where workspace_id = p_workspace_id and status = 'open' and expires_at > now()) >= 200 then
    raise exception 'too_many_open_requests' using errcode = '54000';
  end if;

  insert into public.payment_requests
    (workspace_id, created_by, amount_minor, currency, destination_type, destination_value,
     recipient_display, reference, expires_at, token_hash, idempotency_key)
  values
    (p_workspace_id, auth.uid(), p_amount_minor, p_currency, p_destination_type, v_dest,
     v_display, v_ref, p_expires_at, p_token_hash, p_idempotency_key)
  returning id into v_id;

  insert into public.payment_request_events (workspace_id, payment_request_id, event_type, actor_user_id, metadata)
  values (p_workspace_id, v_id, 'created', auth.uid(),
          jsonb_build_object('amount_minor', p_amount_minor, 'currency', p_currency, 'expires_at', p_expires_at));
  perform public.record_space_audit_event(p_workspace_id, 'payment_request.created', 'payment_request', v_id, null,
          jsonb_build_object('amount_minor', p_amount_minor, 'currency', p_currency));
  return v_id;
end;
$$;
revoke all on function public.create_payment_request(uuid, bigint, text, text, text, text, text, timestamptz, text, text) from public;
grant execute on function public.create_payment_request(uuid, bigint, text, text, text, text, text, timestamptz, text, text) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Shared guard for the three state-changing RPCs: the request creator or a
-- workspace owner; only from 'open' (and, for non-cancel, not yet expired).
-- ---------------------------------------------------------------------------
create or replace function public._payment_request_for_update(p_id uuid, p_require_unexpired boolean)
returns public.payment_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.payment_requests%rowtype;
begin
  select * into r from public.payment_requests where id = p_id for update;
  if not found
     or not (public.is_workspace_member(r.workspace_id, 'member')
             and (r.created_by = auth.uid() or public.is_workspace_member(r.workspace_id, 'owner'))) then
    raise exception 'payment_request_not_found' using errcode = 'P0002';
  end if;
  if r.status <> 'open' then
    raise exception 'invalid_state_transition' using errcode = '22023';
  end if;
  if p_require_unexpired and r.expires_at <= now() then
    raise exception 'payment_request_expired' using errcode = '22023';
  end if;
  return r;
end;
$$;
revoke all on function public._payment_request_for_update(uuid, boolean) from public;

create or replace function public.cancel_payment_request(p_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare r public.payment_requests%rowtype;
begin
  r := public._payment_request_for_update(p_id, false);
  update public.payment_requests set status = 'cancelled', cancelled_at = now() where id = p_id;
  insert into public.payment_request_events (workspace_id, payment_request_id, event_type, actor_user_id)
  values (r.workspace_id, p_id, 'cancelled', auth.uid());
  perform public.record_space_audit_event(r.workspace_id, 'payment_request.cancelled', 'payment_request', p_id);
end; $$;
revoke all on function public.cancel_payment_request(uuid) from public;
grant execute on function public.cancel_payment_request(uuid) to authenticated, service_role;

-- The OWNER'S OWN statement that they were paid. Not verification; labelled so.
create or replace function public.mark_payment_request_paid_by_owner(p_id uuid, p_note text default null)
returns void language plpgsql security definer set search_path = public as $$
declare r public.payment_requests%rowtype;
begin
  r := public._payment_request_for_update(p_id, true);
  update public.payment_requests
  set status = 'marked_paid_by_owner', paid_marked_at = now(), paid_marked_note = left(nullif(trim(p_note), ''), 200)
  where id = p_id;
  insert into public.payment_request_events (workspace_id, payment_request_id, event_type, actor_user_id, metadata)
  values (r.workspace_id, p_id, 'marked_paid_by_owner', auth.uid(), jsonb_build_object('verified', false));
  perform public.record_space_audit_event(r.workspace_id, 'payment_request.marked_paid', 'payment_request', p_id);
end; $$;
revoke all on function public.mark_payment_request_paid_by_owner(uuid, text) from public;
grant execute on function public.mark_payment_request_paid_by_owner(uuid, text) to authenticated, service_role;

-- A human links the real incoming transaction that settled this request.
-- Must be: same workspace, settled, direction 'in', same currency, EXACT amount,
-- and not already linked to another request.
create or replace function public.link_payment_request_transaction(p_id uuid, p_transaction_id uuid)
returns void language plpgsql security definer set search_path = public as $$
declare
  r public.payment_requests%rowtype;
  t public.transactions%rowtype;
begin
  r := public._payment_request_for_update(p_id, false);
  select * into t from public.transactions where id = p_transaction_id and workspace_id = r.workspace_id;
  if not found then
    raise exception 'transaction_not_found' using errcode = 'P0002';
  end if;
  if t.direction <> 'in' or t.settlement_state is distinct from 'settled' or t.dedupe_state = 'merged'
     or t.currency <> r.currency or t.principal_effect_rwf is distinct from r.amount_minor then
    raise exception 'transaction_does_not_match' using errcode = '22023';
  end if;
  if exists (select 1 from public.payment_requests where matched_transaction_id = p_transaction_id) then
    raise exception 'transaction_already_linked' using errcode = '23505';
  end if;
  update public.payment_requests set status = 'matched', matched_transaction_id = p_transaction_id where id = p_id;
  insert into public.payment_request_events (workspace_id, payment_request_id, event_type, actor_user_id, metadata)
  values (r.workspace_id, p_id, 'matched', auth.uid(), jsonb_build_object('transaction_id', p_transaction_id));
  perform public.record_space_audit_event(r.workspace_id, 'payment_request.matched', 'payment_request', p_id, null,
          jsonb_build_object('transaction_id', p_transaction_id));
end; $$;
revoke all on function public.link_payment_request_transaction(uuid, uuid) from public;
grant execute on function public.link_payment_request_transaction(uuid, uuid) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- resolve_payment_request: the PUBLIC (anon) resolver. Takes the SHA-256 hex
-- of the token (the web layer hashes; the raw token never reaches the DB) and
-- returns ONLY what a payer needs. Destination is withheld unless open and
-- unexpired. Unknown / malformed digests return no row. No workspace, owner,
-- id, history. The web route must rate-limit by IP (not possible here).
-- ---------------------------------------------------------------------------
create or replace function public.resolve_payment_request(p_token_hash text)
returns table (
  status text,
  amount_minor bigint,
  currency text,
  recipient_display text,
  reference text,
  expires_at timestamptz,
  destination_type text,
  destination_value text
)
language sql
security definer
set search_path = public
stable
as $$
  select
    case when r.status = 'open' and r.expires_at <= now() then 'expired' else r.status end,
    r.amount_minor, r.currency::text, r.recipient_display, r.reference, r.expires_at,
    case when r.status = 'open' and r.expires_at > now() then r.destination_type end,
    case when r.status = 'open' and r.expires_at > now() then r.destination_value end
  from public.payment_requests r
  where p_token_hash ~ '^[0-9a-f]{64}$' and r.token_hash = p_token_hash;
$$;
revoke all on function public.resolve_payment_request(text) from public;
grant execute on function public.resolve_payment_request(text) to anon, authenticated, service_role;
comment on function public.resolve_payment_request is
  'Public resolver for a shared payment request. Minimum fields; destination only while open and unexpired. A resolved request is NOT proof of payment.';

-- ===========================================================================
-- 6. expire_stale_pairing_sessions - service-role cleanup
-- ===========================================================================

create or replace function public.expire_stale_pairing_sessions()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  update public.pairing_sessions
  set status = 'expired'
  where status = 'pending'
    and expires_at <= clock_timestamp();
  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

comment on function public.expire_stale_pairing_sessions() is
  'Service-role cleanup: flips expired pending pairing sessions to status=expired. Safe to run on a schedule.';
revoke all on function public.expire_stale_pairing_sessions() from public;
grant execute on function public.expire_stale_pairing_sessions() to service_role;

  set status = 'unmatched', transaction_id = null, matched_by = null, candidate_count = 0, auto_link_disabled = true
  where id = p_receipt;
  perform public.record_space_audit_event(r.workspace_id, 'utility_receipt.unlinked', 'utility_receipt', p_receipt, null,
    jsonb_build_object('transaction_id', r.transaction_id));
end;
$$;

-- ---------------------------------------------------------------------------
-- Reveal: now also serves tokens from receipts. Authorisation is unchanged
-- (member+ AND visibility of the payment's source), as are the 20/hour limit and
-- the audit row. Returns WHICH row the sealed value came from, so the app binds
-- the right AAD ('<id>:utility_token' for the E5 table, '<id>:utility_receipt').
-- ---------------------------------------------------------------------------
drop function public.reveal_transaction_sensitive_detail(uuid, text);
create function public.reveal_transaction_sensitive_detail(
  p_transaction_id uuid,
  p_kind text default 'utility_token'
)
returns table (source text, row_id uuid, key_id text, nonce text, ciphertext text)
language plpgsql
security definer
set search_path = public
as $$
declare
  t record;
  d public.transaction_sensitive_details%rowtype;
  rc public.utility_receipts%rowtype;
begin
  if auth.uid() is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  select tx.workspace_id, tx.financial_source_id into t
  from public.transactions tx where tx.id = p_transaction_id;

  if not found
     or not public.is_workspace_member(t.workspace_id, 'member')
     or not public.can_view_source_in_space(t.financial_source_id, t.workspace_id) then
    raise exception 'sensitive_detail_not_found' using errcode = 'P0002';
  end if;

  select * into d from public.transaction_sensitive_details
  where transaction_id = p_transaction_id and kind = p_kind;
  if not found then
    select * into rc from public.utility_receipts
    where transaction_id = p_transaction_id and status = 'matched' and token_ciphertext is not null;
    if not found or p_kind <> 'utility_token' then
      raise exception 'sensitive_detail_not_found' using errcode = 'P0002';
    end if;
  end if;

  if (select count(*) from public.space_audit_events
        where actor_user_id = auth.uid()
          and event_type = 'transaction.sensitive_revealed'
          and created_at > now() - interval '1 hour') >= 20 then
    raise exception 'rate_limited' using errcode = '54000';
  end if;

  perform public.record_space_audit_event(
    t.workspace_id, 'transaction.sensitive_revealed', 'transaction', p_transaction_id,
    null, jsonb_build_object('kind', p_kind));

  if d.transaction_id is not null then
    return query select 'transaction'::text, d.transaction_id, d.key_id, d.nonce, d.ciphertext;
  else
    return query select 'receipt'::text, rc.id, rc.token_key_id, rc.token_nonce, rc.token_ciphertext;
  end if;
end;
$$;
revoke all on function public.reveal_transaction_sensitive_detail(uuid, text) from public;
grant execute on function public.reveal_transaction_sensitive_detail(uuid, text) to authenticated, service_role;

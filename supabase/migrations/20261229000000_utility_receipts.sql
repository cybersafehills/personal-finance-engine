-- OneLedger 3.0 E7: prepaid-electricity ("Cash Power") receipts (docs/adr/0020).
-- The vendor SMS (NOT the MoMo confirmation) carries the token, kWh and meter.
-- It arrives separately - before OR after the MoMo payment - so a receipt is its
-- own record that is LINKED to the payment transaction:
--   * exactly one plausible payment  -> linked automatically ('auto');
--   * several                        -> 'ambiguous': the user chooses;
--   * none yet                       -> 'unmatched': linked when the payment
--                                       arrives (trigger on transactions).
-- ADDITIVE. Personal data is minimised: only the LAST FOUR digits of the meter
-- are kept; the meter owner's name is never read; the token is stored only as
-- application-encrypted ciphertext (same AES-GCM keyring as E5) and the client
-- roles can never SELECT it - they get column-level grants that leave the
-- ciphertext columns out.

create table public.utility_receipts (
  id uuid primary key,  -- generated by the writer: it is bound into the ciphertext (AAD)
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  format text not null check (format in ('cashpower_en', 'tokeni_rw')),
  amount_rwf bigint not null check (amount_rwf > 0),
  -- kWh x 1000 as an integer (11.9 kWh = 11900): no floating point.
  kwh_milli bigint not null check (kwh_milli > 0),
  meter_last4 text check (meter_last4 is null or meter_last4 ~ '^[0-9]{4}$'),
  -- sha256 hex of the vendor's own transaction reference (or of the token when
  -- the message has none): makes a re-delivered SMS a no-op without storing it.
  vendor_ref_hash text not null check (vendor_ref_hash ~ '^[0-9a-f]{64}$'),
  receipt_at timestamptz not null,
  -- Sealed token; all three NULL when it was not captured (no key / switched off).
  token_key_id text check (token_key_id is null or token_key_id ~ '^[A-Za-z0-9_-]{1,32}$'),
  token_nonce text,
  token_ciphertext text,
  -- Safe to show: whether a token was kept (the ciphertext itself is not selectable).
  has_token boolean generated always as (token_ciphertext is not null) stored,
  status text not null default 'unmatched'
    check (status in ('unmatched', 'ambiguous', 'matched', 'ignored')),
  transaction_id uuid,
  matched_by text check (matched_by is null or matched_by in ('auto', 'user')),
  candidate_count integer not null default 0 check (candidate_count >= 0),
  -- set when the user un-links a wrong auto-match, so it is not re-linked behind their back
  auto_link_disabled boolean not null default false,
  created_at timestamptz not null default now(),
  constraint utility_receipts_vendor_ref_unique unique (workspace_id, vendor_ref_hash),
  constraint utility_receipts_token_all_or_none check (
    (token_key_id is null) = (token_nonce is null) and (token_nonce is null) = (token_ciphertext is null)),
  constraint utility_receipts_matched_consistent check (
    (status = 'matched') = (transaction_id is not null)
    and (status = 'matched') = (matched_by is not null)),
  -- A receipt has no meaning without its payment once linked: erasing the
  -- transaction removes it (cascade), never leaves a half-linked row.
  constraint utility_receipts_txn_same_workspace
    foreign key (workspace_id, transaction_id)
    references public.transactions (workspace_id, id) on delete cascade
);
create unique index idx_utility_receipts_one_per_txn
  on public.utility_receipts (transaction_id) where transaction_id is not null;
create index idx_utility_receipts_open
  on public.utility_receipts (workspace_id, amount_rwf) where status in ('unmatched', 'ambiguous');

alter table public.utility_receipts enable row level security;
create policy utility_receipts_select_visible on public.utility_receipts
  for select to authenticated
  using (
    public.is_workspace_member(workspace_id)
    -- the subquery runs under the caller's own RLS on transactions, so source
    -- visibility (who may see the payment) is inherited for linked receipts
    and (transaction_id is null
         or exists (select 1 from public.transactions t where t.id = utility_receipts.transaction_id))
  );
revoke all on public.utility_receipts from anon, authenticated;
-- COLUMN-level grant: the token_* columns are deliberately not listed.
grant select (id, workspace_id, format, amount_rwf, kwh_milli, meter_last4, receipt_at,
              has_token, status, transaction_id, matched_by, candidate_count, created_at)
  on public.utility_receipts to authenticated;
grant select, insert, update, delete on public.utility_receipts to service_role;

comment on table public.utility_receipts is
  'Prepaid-electricity receipts parsed from the vendor SMS and linked to the MoMo payment. Token is application-encrypted ciphertext that no client role can select; only the last 4 digits of the meter are kept.';

-- ---------------------------------------------------------------------------
-- Linking. Candidates = settled, outgoing payments of EXACTLY the receipt amount
-- in the same workspace, of a type a utility purchase can have (never a person-
-- to-person send or a cash withdrawal), not already claimed by another receipt,
-- paid shortly before the receipt (24 h) or a moment after it (1 h of skew).
-- ---------------------------------------------------------------------------
create or replace function public._utility_receipt_candidates(p_receipt uuid)
returns setof uuid
language sql
stable
security definer
set search_path = public
as $$
  select t.id
  from public.utility_receipts r
  join public.transactions t on t.workspace_id = r.workspace_id
  where r.id = p_receipt
    and t.direction = 'out'
    and t.settlement_state = 'settled'
    and t.dedupe_state <> 'merged'
    and t.transaction_type in ('merchant_payment', 'bill_payment', 'other')
    and t.amount_rwf = r.amount_rwf
    and t.occurred_at between r.receipt_at - interval '24 hours' and r.receipt_at + interval '1 hour'
    and not exists (select 1 from public.utility_receipts x where x.transaction_id = t.id)
  order by t.occurred_at desc;
$$;
revoke all on function public._utility_receipt_candidates(uuid) from public;

create or replace function public._link_utility_receipt(p_receipt uuid)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.utility_receipts%rowtype;
  v_ids uuid[];
begin
  select * into r from public.utility_receipts where id = p_receipt for update;
  if not found or r.status in ('matched', 'ignored') then
    return coalesce(r.status, 'missing');
  end if;
  if r.auto_link_disabled then
    return r.status;
  end if;

  select coalesce(array_agg(c), '{}') into v_ids from public._utility_receipt_candidates(p_receipt) c;
  if cardinality(v_ids) = 1 then
    update public.utility_receipts
    set status = 'matched', transaction_id = v_ids[1], matched_by = 'auto', candidate_count = 1
    where id = p_receipt;
    return 'matched';
  end if;
  update public.utility_receipts
  set status = case when cardinality(v_ids) > 1 then 'ambiguous' else 'unmatched' end,
      candidate_count = cardinality(v_ids)
  where id = p_receipt;
  return case when cardinality(v_ids) > 1 then 'ambiguous' else 'unmatched' end;
end;
$$;
revoke all on function public._link_utility_receipt(uuid) from public;

-- A payment arriving AFTER its receipt links it.
create or replace function public._utility_receipt_on_transaction()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  rid uuid;
begin
  if new.direction = 'out' and new.settlement_state = 'settled'
     and new.transaction_type in ('merchant_payment', 'bill_payment', 'other') then
    for rid in
      select r.id from public.utility_receipts r
      where r.workspace_id = new.workspace_id
        and r.status in ('unmatched', 'ambiguous')
        and r.amount_rwf = new.amount_rwf
    loop
      begin
        perform public._link_utility_receipt(rid);
      exception when others then
        null; -- linking is best-effort: it must never fail the payment's own insert
      end;
    end loop;
  end if;
  return null;
end;
$$;
revoke all on function public._utility_receipt_on_transaction() from public;
create trigger trg_utility_receipt_on_transaction
  after insert or update of settlement_state on public.transactions
  for each row execute function public._utility_receipt_on_transaction();

-- ---------------------------------------------------------------------------
-- store_utility_receipt: the ingest path (service role only). Idempotent on the
-- vendor reference. Returns the receipt id, its status and whether it was new.
-- ---------------------------------------------------------------------------
create or replace function public.store_utility_receipt(
  p_id uuid,
  p_workspace_id uuid,
  p_format text,
  p_amount_rwf bigint,
  p_kwh_milli bigint,
  p_meter_last4 text,
  p_vendor_ref_hash text,
  p_receipt_at timestamptz,
  p_token_key_id text,
  p_token_nonce text,
  p_token_ciphertext text
)
returns table (receipt_id uuid, status text, created boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_status text;
begin
  insert into public.utility_receipts
    (id, workspace_id, format, amount_rwf, kwh_milli, meter_last4, vendor_ref_hash, receipt_at,
     token_key_id, token_nonce, token_ciphertext)
  values
    (p_id, p_workspace_id, p_format, p_amount_rwf, p_kwh_milli, p_meter_last4, p_vendor_ref_hash, p_receipt_at,
     p_token_key_id, p_token_nonce, p_token_ciphertext)
  on conflict (workspace_id, vendor_ref_hash) do nothing
  returning utility_receipts.id into v_id;

  if v_id is null then
    select r.id, r.status into v_id, v_status
    from public.utility_receipts r
    where r.workspace_id = p_workspace_id and r.vendor_ref_hash = p_vendor_ref_hash;
    return query select v_id, v_status, false;
    return;
  end if;

  v_status := public._link_utility_receipt(v_id);
  return query select v_id, v_status, true;
end;
$$;
revoke all on function public.store_utility_receipt(uuid, uuid, text, bigint, bigint, text, text, timestamptz, text, text, text) from public;
grant execute on function public.store_utility_receipt(uuid, uuid, text, bigint, bigint, text, text, timestamptz, text, text, text) to service_role;

-- ---------------------------------------------------------------------------
-- User actions (member+, audited): confirm a match, un-link a wrong one, ignore.
-- ---------------------------------------------------------------------------
create or replace function public.confirm_utility_receipt(p_receipt uuid, p_transaction uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.utility_receipts%rowtype;
  t public.transactions%rowtype;
begin
  select * into r from public.utility_receipts where id = p_receipt for update;
  if not found or not public.is_workspace_member(r.workspace_id, 'member') or r.status = 'matched' then
    raise exception 'receipt_not_found' using errcode = 'P0002';
  end if;
  select * into t from public.transactions where id = p_transaction and workspace_id = r.workspace_id;
  if not found or not public.can_view_source_in_space(t.financial_source_id, t.workspace_id) then
    raise exception 'receipt_not_found' using errcode = 'P0002';
  end if;
  if t.direction <> 'out' or t.settlement_state is distinct from 'settled' or t.dedupe_state = 'merged'
     or t.amount_rwf <> r.amount_rwf
     or exists (select 1 from public.utility_receipts x where x.transaction_id = t.id) then
    raise exception 'receipt_does_not_match' using errcode = '22023';
  end if;
  update public.utility_receipts
  set status = 'matched', transaction_id = t.id, matched_by = 'user', auto_link_disabled = false
  where id = p_receipt;
  perform public.record_space_audit_event(r.workspace_id, 'utility_receipt.confirmed', 'utility_receipt', p_receipt, null,
    jsonb_build_object('transaction_id', t.id));
end;
$$;
revoke all on function public.confirm_utility_receipt(uuid, uuid) from public;
grant execute on function public.confirm_utility_receipt(uuid, uuid) to authenticated, service_role;

create or replace function public.unlink_utility_receipt(p_receipt uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.utility_receipts%rowtype;
begin
  select * into r from public.utility_receipts where id = p_receipt for update;
  if not found or not public.is_workspace_member(r.workspace_id, 'member') or r.status <> 'matched' then
    raise exception 'receipt_not_found' using errcode = 'P0002';
  end if;
